import { join } from "node:path";
import { cavemanAgentDir } from "../integrations/caveman-code.ts";
import { buildIntegration, installExtensionFile, type InstallGjcIntegrationResult } from "./install-gjc-integration.ts";

export const CAVEMAN_INTEGRATION_OWNERSHIP_BANNER = "// Generated by herdr-web-ui Caveman Code integration installer; do not edit.";

export interface InstallCavemanIntegrationOptions {
  /** Caveman Code's agent directory; by default its own, ~/.cave/agent. */
  agentDir?: string;
  remove?: boolean;
  build?: () => Promise<string>;
}

/** Install or remove only herdr-web-ui.js in Caveman Code's own extensions directory, which it loads by itself. */
export default async function installCavemanIntegration(options: InstallCavemanIntegrationOptions = {}): Promise<InstallGjcIntegrationResult> {
  return installExtensionFile(join(options.agentDir ?? cavemanAgentDir(), "extensions", "herdr-web-ui.js"), CAVEMAN_INTEGRATION_OWNERSHIP_BANNER, {
    remove: options.remove,
    build: options.build ?? (() => buildIntegration("caveman-code", "node")),
  });
}

function parseArguments(args: string[]): InstallCavemanIntegrationOptions {
  const options: InstallCavemanIntegrationOptions = {};
  for (const arg of args) {
    if (arg === "--remove") options.remove = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

if (import.meta.main) {
  try {
    const result = await installCavemanIntegration(parseArguments(Bun.argv.slice(2)));
    if (result.action === "installed") {
      console.log(`Installed Caveman Code integration: ${result.path}`);
      console.log("Restart existing caveman-code sessions to load the integration.");
    } else {
      console.log(`Removed Caveman Code integration: ${result.path}`);
      console.log("Restart existing caveman-code sessions for the change to take effect.");
    }
  } catch (error) {
    console.error(`Caveman Code integration installer failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
